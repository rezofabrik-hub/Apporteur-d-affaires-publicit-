function strate(slug) {
  const c = communes[slug];
  if (!c) return null;
  for (let i = 0; i < STRATES.length; i++) {
    if (c.pop < STRATES[i][0]) return STRATES[i][1];
  }
  return STRATES[STRATES.length - 1][1];
}

